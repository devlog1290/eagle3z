function openYouTube() {
    window.location.href = "youtube://";
    
    setTimeout(() => {
        window.location.href = "https://youtube.com";
    }, 1500);
}

function openTikTok() {
    window.location.href = "tiktok://";

    setTimeout(() => {
        window.location.href = "https://tiktok.com";
    }, 1500);
}
